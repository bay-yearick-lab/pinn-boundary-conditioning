"""Cost of the a-priori diagnostic versus the sweep it replaces, plus recorded
training wall times.

    python benchmarks/run_benchmarks.py            # writes benchmarks/results.md

Part 1 (measured here, CPU, float64 dense linear algebra): on the 3D Poisson and
3D anisotropic testbeds (n = 216 features, m = 1600 interior, b = 72 boundary
points) time
  - the diagnostic constants (rho, nu, mu, sigma_B, kappa_red) from one
    constrained least-squares solve plus two small eigenproblems, and
  - the confirming 85-weight direct-solve sweep (penalized normal equations and
    a 2-norm condition number per weight).
Part 2 (read from data/): per-run wall time of the trained PINN / DeepONet
sweeps and of the finite-difference reference solves, as recorded by the
experiment scripts, with the device stored in the records.
"""

import os

# Small dense problems: a few BLAS threads beat oversubscribing every core.
for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(_v, "4")

import json
import platform
import sys
import time
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
from exp_diagnostic_3d import (build_poisson_3d, build_stiff_3d,  # noqa: E402
                               diagnostic_constants, leak_grid_from_constants,
                               run_sweep, valley_grid_from_constants)

DATA = ROOT / "data"
OUT = Path(__file__).resolve().parent / "results.md"


def best_of(fn, repeats=3):
    times = []
    for _ in range(repeats):
        t0 = time.perf_counter()
        out = fn()
        times.append(time.perf_counter() - t0)
    return min(times), out


def part1(seeds=(0, 1, 2)):
    rows = []
    for name, builder in (("3D Poisson", build_poisson_3d),
                          ("3D anisotropic 1:40:1600", build_stiff_3d)):
        t_c, t_s, ratios = [], [], []
        for seed in seeds:
            p = builder(seed=seed)
            A, f, B, g = p["A"], p["f"], p["B"], p["g"]
            tc, c = best_of(lambda: diagnostic_constants(A, f, B, g))
            lams = np.concatenate([leak_grid_from_constants(c),
                                   valley_grid_from_constants(c)])
            ts, (leaks, kaps) = best_of(lambda: run_sweep(A, f, B, g, lams), repeats=1)
            pred = c["rho"] * c["sigmaB"] ** 2 / c["mu"]
            nl = len(leak_grid_from_constants(c))
            ratios.append(leaks[nl - 1] * kaps[nl - 1] / pred)
            t_c.append(tc)
            t_s.append(ts)
        rows.append(dict(testbed=name, shape=f"{A.shape[0]}+{B.shape[0]} x {A.shape[1]}",
                         n_weights=len(lams), t_constants=float(np.median(t_c)),
                         t_sweep=float(np.median(t_s)),
                         ratio=float(np.median(ratios))))
    return rows


def jsonl(name):
    return [json.loads(line) for line in (DATA / name).read_text().splitlines()]


def part2():
    rows2d = []
    for name, label, steps in (("pinn_sweep.jsonl", "2D Poisson tanh PINN, 4x64", 20000),
                               ("burgers_sweep.jsonl", "Viscous Burgers tanh PINN", 20000),
                               ("operator_sweep.jsonl", "Physics-informed DeepONet", 15000)):
        by_mode = defaultdict(list)
        for r in jsonl(name):
            if r.get("steps") == steps and r.get("dtype", "float32") == "float32":
                by_mode[r["mode"]].append(r["wall_s"])
        for mode in ("soft", "hard"):
            w = by_mode[mode]
            rows2d.append((label, mode, steps, len(w), float(np.median(w))))
    d = json.loads((DATA / "trained_3d.json").read_text())
    rows3d = []
    steps = d["config"]["sweep_steps"]
    for key, label in (("P1_poisson", "3D Poisson"), ("P2_stiff", "3D anisotropic 1:40:1600")):
        soft = [w for v in d[key]["sweep"].values() for w in v["wall_s"]]
        hard = d[key]["hard"]["wall_s"]
        fd = d[key]["fd_reference"]
        rows3d.append((label, len(soft), float(np.median(soft)), len(hard),
                       float(np.median(hard)), fd["wall_s"], fd["nnz"]))
    return rows2d, rows3d, steps, d["config"]["device"], d["total_wall_s"]


def main():
    r1 = part1()
    r2, r3, steps3d, dev, total3d = part2()
    lines = ["# Benchmarks", "",
             f"Generated by `python benchmarks/run_benchmarks.py`; CPU timings measured on "
             f"{platform.machine()}, NumPy {np.__version__}, Python "
             f"{platform.python_version()}, {os.environ['OPENBLAS_NUM_THREADS']} BLAS threads.", "",
             "## A-priori diagnostic vs confirming sweep (CPU, float64, median of 3 seeds)", "",
             "The diagnostic needs one constrained least-squares solve and two small "
             "eigenproblems; the sweep it replaces needs a penalized solve and a "
             "condition number at every weight.", "",
             "| Testbed | Rows x features | Diagnostic constants | Confirming sweep | Weights | measured / predicted product |",
             "| --- | --- | ---: | ---: | ---: | ---: |"]
    for r in r1:
        lines.append(f"| {r['testbed']} | {r['shape']} | {r['t_constants']*1e3:.0f} ms | "
                     f"{r['t_sweep']:.2f} s | {r['n_weights']} | {r['ratio']:.4f} |")
    lines += ["", f"## GPU training, 6x128 tanh PINN, 8000 + 2000 collocation points ({dev})", "",
              f"Adam, {steps3d} iterations per run, float32 with TF32 matmuls. "
              "Reference: 7-point finite differences on a 49^3 grid, sparse LU on the CPU.", "",
              "| Problem | Soft runs | Soft, median per run | Hard runs | Hard, median per run | FD reference (nnz) |",
              "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for label, ns, ws, nh, wh, wfd, nnz in r3:
        lines.append(f"| {label} | {ns} | {ws:.1f} s | {nh} | {wh:.1f} s | {wfd:.1f} s ({nnz}) |")
    lines += ["", f"The complete 3D study (2 problems, 6 weights x 8 seeds, 8 hard twins each, "
              f"warmups, tangent-kernel constants and FD references) ran in {total3d/60:.0f} min.",
              "", "## 2D training runs (recorded wall time per run)", "",
              "| Model | Arm | Adam steps | Runs | Median wall time |",
              "| --- | --- | ---: | ---: | ---: |"]
    for label, mode, steps, n, w in r2:
        lines.append(f"| {label} | {mode} | {steps} | {n} | {w:.1f} s |")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
