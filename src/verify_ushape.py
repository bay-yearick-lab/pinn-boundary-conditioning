"""Verify the U (realizable regime): kappa_eff is the clock, weighting rules
are navigators on it, and the U's floor is the hard-constrained rate.

Realizable, overparameterized testbed: data generated BY the model class
(f = A w_true, g = B w_true), so zero loss is attainable and there is no leak.
The cost of the weight is purely dynamic. Convergence is measured by the
lambda-FREE criterion max(interior residual, boundary residual) <= 1e-8
(comparing lambda-weighted losses across lambda would be apples to oranges).

Checks:
  U1: kappa_eff(lam) is U-shaped with branch slopes -1 and +1.
  U2: GD iterations-to-tolerance are proportional to kappa_eff (log-log slope
      ~1, r > 0.99) over the non-saturated sweep: kappa_eff is the clock.
  U3: the trace-balancing rule lam_hat = tr(A A^T)/tr(B B^T) is a navigator,
      not the floor: its measured budget penalty iters(lam_hat)/iters(lam*)
      equals the predicted kappa(lam_hat)/kappa* within 25%.
  U4: the U's floor matches the hard-constrained (reduced) condition number
      within a factor of 3: an optimally weighted soft penalty can at best
      recover the fence's clock.
"""

import numpy as np
from problems import shifted_sine_features_1d

PASS = True


def check(name, ok, detail=""):
    global PASS
    status = "PASS" if ok else "FAIL"
    if not ok:
        PASS = False
    print(f"[{status}] {name} {detail}")


def build_realizable(n_feat=120, m=30, b=2, seed=0):
    rng = np.random.default_rng(seed)
    xs = np.sort(rng.uniform(0.0, 1.0, size=m))
    Phi_i, Lap_i = shifted_sine_features_1d(xs, n_feat)
    A = -Lap_i / np.sqrt(m)
    sb = np.array([0.0, 1.0])
    Phi_b, _ = shifted_sine_features_1d(sb, n_feat)
    B = Phi_b / np.sqrt(b)
    s = np.linalg.norm(A, axis=0)
    A, B = A / s[None, :], B / s[None, :]
    j = np.arange(1, n_feat + 1)
    w_true = rng.normal(size=n_feat) / j ** 2
    f = A @ w_true
    g = B @ w_true
    return A, f, B, g, w_true


def kappa_eff(H, tol=1e-11):
    ev = np.linalg.eigvalsh(H)
    nz = ev[ev > ev[-1] * tol]
    return ev[-1] / nz[0]


def gd_iters_to_residual(A, f, B, g, lam, tol=1e-8, tmax=3_000_000):
    """Iterations until max(||Aw-f||, ||Bw-g||) <= tol, exact modal GD."""
    H = A.T @ A + lam * (B.T @ B)
    rhs = A.T @ f + lam * (B.T @ g)
    h, V = np.linalg.eigh(H)
    eta = 1.0 / h[-1]
    c = V.T @ rhs
    nz = h > h[-1] * 1e-13
    a0 = np.where(nz, c / np.where(nz, h, 1.0), 0.0)
    fac = np.abs(1.0 - eta * h)
    AV, BV = A @ V, B @ V
    r_inf = AV @ a0 - f
    s_inf = BV @ a0 - g

    def res(t):
        d = -(a0 * fac ** float(t))
        return max(np.linalg.norm(AV @ d + r_inf), np.linalg.norm(BV @ d + s_inf))

    if res(tmax) > tol:
        return tmax
    lo, hi = 0, tmax
    while lo < hi:
        mid = (lo + hi) // 2
        if res(mid) <= tol:
            hi = mid
        else:
            lo = mid + 1
    return lo


def main():
    A, f, B, g, w_true = build_realizable()
    lams = np.logspace(-3, 6, 19)
    kaps = np.array([kappa_eff(A.T @ A + lam * (B.T @ B)) for lam in lams])
    i_min = int(np.argmin(kaps))
    lam_star, kap_star = lams[i_min], kaps[i_min]
    lo = lams <= lam_star / 30
    hi = lams >= lam_star * 300
    sl_lo = np.polyfit(np.log10(lams[lo]), np.log10(kaps[lo]), 1)[0]
    sl_hi = np.polyfit(np.log10(lams[hi]), np.log10(kaps[hi]), 1)[0]
    print(f"kappa floor {kap_star:.3e} at lam*={lam_star:.3e}")
    check("U1 left branch slope ~ -1", -1.15 < sl_lo < -0.75, f"slope={sl_lo:.3f}")
    check("U1 right branch slope ~ +1", 0.75 < sl_hi < 1.15, f"slope={sl_hi:.3f}")

    iters = np.array([gd_iters_to_residual(A, f, B, g, lam) for lam in lams])
    ok = iters < 3_000_000
    sl, r = np.polyfit(np.log10(kaps[ok]), np.log10(iters[ok]), 1)[0], \
        np.corrcoef(np.log10(kaps[ok]), np.log10(iters[ok]))[0, 1]
    check("U2 iters ~ kappa_eff (clock)", 0.85 < sl < 1.15 and r > 0.99,
          f"slope={sl:.3f} r={r:.4f}")

    lam_ntk = np.trace(A @ A.T) / np.trace(B @ B.T)
    it_ntk = gd_iters_to_residual(A, f, B, g, lam_ntk)
    it_star = iters[i_min]
    kap_ntk = kappa_eff(A.T @ A + lam_ntk * (B.T @ B))
    predicted = kap_ntk / kap_star
    measured = it_ntk / it_star
    check("U3 mis-weighting cost = kappa ratio",
          abs(measured / predicted - 1.0) < 0.25,
          f"lam_ntk={lam_ntk:.2e}: predicted {predicted:.2f}x, measured {measured:.2f}x")

    # U4: floor vs hard-constrained clock
    _, sv, Vt = np.linalg.svd(B, full_matrices=True)
    Z = Vt[len(sv):].T
    Mred = Z.T @ (A.T @ A) @ Z
    kap_red = kappa_eff(Mred)
    check("U4 U-floor ~ hard clock", 1 / 3 < kap_star / kap_red < 3,
          f"kappa*={kap_star:.3e} kappa_red={kap_red:.3e} ratio={kap_star/kap_red:.2f}")

    print("\nALL PASS" if PASS else "\nSOME CHECKS FAILED")
    raise SystemExit(0 if PASS else 1)


if __name__ == "__main__":
    main()
